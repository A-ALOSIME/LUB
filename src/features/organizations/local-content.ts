function normalizeName(value: string) {
  return value
    .normalize("NFKD")
    .replace(/[\u064B-\u065F\u0670\u0640]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ")
    .trim()
    .toLocaleLowerCase("en");
}

export function localOrganizationContent(nameAr: string, typeCode: string) {
  const name = normalizeName(nameAr);
  return profiles.find(profile =>
    profile.typeCode === typeCode &&
    profile.matches.some(match => name.includes(normalizeName(match)))
  );
}
